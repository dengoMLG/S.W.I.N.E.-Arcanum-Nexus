#!/usr/bin/env node
// Собирает мод Arcanum Voices & Screens: modpack/mods/arcanum-voices/ из исходников modpack/voices/.
//   node tools/build-voices-mod.js
//
// Пишет в modpack/mods/arcanum-voices/:
//   gamedata/base/units.ini.arcpatch                — привязка Character и Voice для всех 10 новых юнитов;
//   gamedata/base/reportanim/<CharId>/*.anif        — 70 анимированных экранчиков (120×90, 25 FPS, 7 эмоций × 10 танков);
//   gamedata/base/sounds/speech/<CharId>/*.mp3      — 300 уникальных русских реплик, разложенных по всем игровым ID
//                                                     (включая раненые варианты *w.mp3, т.к. ShowEventMsg не имеет fallback).
//   README.md                                       — описание мода (коммитится в git).
//
// Важно про имена Character (разбор SGameWorld::ShowEventMsg @ 0x4afdf0):
//   - первый символ 'R' (0x52) задаёт канал кроликов, 'P' — канал свиней (+100);
//   - atoi(Character + 1) должен быть в 1..8 или 12, чтобы движок проигрывал весь набор из 7 анимаций
//     (3mp, 5mp, success, laugh, spec, death, death2); номера >= 13 движок считает героями (только 5mp и death).
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'modpack/voices');
const RAVEN_SRC = path.join(ROOT, 'modpack/raven');
const DST = path.join(ROOT, 'modpack/mods/arcanum-voices');
const GD = path.join(DST, 'gamedata/base');

const scripts = JSON.parse(fs.readFileSync(path.join(SRC, 'voice_scripts.json'), 'utf8'));
const ravenScripts = fs.existsSync(path.join(RAVEN_SRC, 'raven_voice_scripts.json'))
  ? JSON.parse(fs.readFileSync(path.join(RAVEN_SRC, 'raven_voice_scripts.json'), 'utf8'))
  : { units: [] };
const RAVEN_RACE = require('./raven-race');

function expandRange(ranges) {
  const out = [];
  for (const [a, b] of ranges) for (let i = a; i <= b; i++) out.push(i);
  return out;
}

// Соответствие категорий наших реплик числовым ID событий из swineHD.exe / ru.pak
const SPEECH_MAP = {
  pig: [
    { cat: 'select',            n: [[16, 30]],                          w: [[16, 25]] },
    { cat: 'confirm_move',      n: [[122, 147]],                        w: [[122, 129], [136, 147]] },
    { cat: 'attack',            n: [[148, 157], [306, 320]],            w: [[148, 150]] },
    { cat: 'spec',              n: [[162, 165], [178, 189], [203, 209], [374, 375]], w: [[162, 165], [178, 189], [203, 209]] },
    { cat: 'spot_enemy',        n: [[299, 305]],                        w: [[299, 305]] },
    { cat: 'kill_laugh',        n: [[321, 332]],                        w: [] },
    { cat: 'under_fire_damage', n: [[333, 337], [345, 349], [357, 367]], w: [[335, 337], [345, 349], [357, 367]] },
    { cat: 'low_supply',        n: [[338, 344], [350, 356]],            w: [[338, 344], [350, 356]] },
    { cat: 'death',             n: [[368, 373]],                        w: [] },
  ],
  rabbit: [
    { cat: 'select',            n: [[1, 15]],                           w: [[3, 10]] },
    { cat: 'confirm_move',      n: [[31, 56]],                          w: [[31, 38], [45, 56]] },
    { cat: 'attack',            n: [[57, 66], [218, 232]],              w: [[57, 59]] },
    { cat: 'spec',              n: [[67, 80], [87, 92], [100, 118], [286, 287]], w: [[67, 80], [87, 92], [100, 118]] },
    { cat: 'spot_enemy',        n: [[211, 217]],                        w: [[211, 217]] },
    { cat: 'kill_laugh',        n: [[233, 244]],                        w: [] },
    { cat: 'under_fire_damage', n: [[245, 249], [257, 261], [269, 279]], w: [[247, 249], [257, 261], [269, 279]] },
    { cat: 'low_supply',        n: [[250, 256], [262, 268]],            w: [[250, 256], [262, 268]] },
    { cat: 'death',             n: [[280, 285]],                        w: [] },
  ],
};

fs.rmSync(path.join(DST, 'gamedata'), { recursive: true, force: true });
fs.mkdirSync(GD, { recursive: true });

const patchLines = [
  '; Arcanum Voices & Screens: HUD portraits (reportanim) and Russian voice lines for all 10 new Arcanum Units.',
  '; Auto-generated by tools/build-voices-mod.js.',
  '',
];

let anifFiles = 0, anifBytes = 0;
let speechFiles = 0, speechBytes = 0;

const allVoiceUnits = [
  ...scripts.units.map(u => ({
    section: u.section,
    charId: u.char_id,
    voiceId: u.voice_id,
    srcAnifDir: path.join(SRC, 'reportanim', u.char_id),
    srcLinesDir: path.join(SRC, 'lines', u.char_id),
  })),
  ...ravenScripts.units.map(u => {
    const ru = RAVEN_RACE.UNITS.find(x => x.model === u.id);
    if (!ru) throw new Error(`Missing Raven unit in raven-race.js for model ${u.id}`);
    const charId = ru.set.Character;
    const voiceId = ru.set.Voice;
    return {
      section: ru.s,
      charId,
      voiceId,
      srcAnifDir: path.join(RAVEN_SRC, 'reportanim', u.char_id),
      srcLinesDir: path.join(RAVEN_SRC, 'lines', u.char_id),
    };
  }),
];

for (const u of allVoiceUnits) {
  const charId = u.charId;
  const voiceId = u.voiceId;
  const race = charId.startsWith('P') ? 'pig' : 'rabbit';

  patchLines.push(`[${u.section}]`);
  patchLines.push(`Character = ${charId}`);
  patchLines.push(`Voice = ${voiceId}`);
  patchLines.push('');

  // 1. Copy 7 .anif animations
  const srcAnifDir = u.srcAnifDir;
  const dstAnifDir = path.join(GD, 'reportanim', charId);
  fs.mkdirSync(dstAnifDir, { recursive: true });
  for (const em of ['3mp', '5mp', 'success', 'laugh', 'spec', 'death', 'death2']) {
    const srcF = path.join(srcAnifDir, `${em}.anif`);
    const dstF = path.join(dstAnifDir, `${em}.anif`);
    if (!fs.existsSync(srcF)) throw new Error(`Missing ANIF: ${srcF}`);
    fs.copyFileSync(srcF, dstF);
    anifFiles++;
    anifBytes += fs.statSync(dstF).size;
  }

  // 2. Expand 30 unique MP3 lines across all numeric game event IDs + wounded (*w) variants
  const dstSpeechDir = path.join(GD, 'sounds/speech', voiceId);
  fs.mkdirSync(dstSpeechDir, { recursive: true });

  for (const rule of SPEECH_MAP[race]) {
    const catDir = path.join(u.srcLinesDir, rule.cat);
    const pool = fs.readdirSync(catDir).filter(f => f.endsWith('.mp3')).sort().map(f => path.join(catDir, f));
    if (!pool.length) throw new Error(`Empty voice category: ${catDir}`);

    const nIds = expandRange(rule.n);
    for (let i = 0; i < nIds.length; i++) {
      const idStr = String(nIds[i]).padStart(3, '0');
      const srcMp3 = pool[i % pool.length];
      const dstMp3 = path.join(dstSpeechDir, `${idStr}.mp3`);
      fs.copyFileSync(srcMp3, dstMp3);
      speechFiles++;
      speechBytes += fs.statSync(dstMp3).size;
    }

    const wIds = expandRange(rule.w);
    for (let i = 0; i < wIds.length; i++) {
      const idStr = String(wIds[i]).padStart(3, '0');
      const srcMp3 = pool[i % pool.length];
      const dstMp3 = path.join(dstSpeechDir, `${idStr}w.mp3`);
      fs.copyFileSync(srcMp3, dstMp3);
      speechFiles++;
      speechBytes += fs.statSync(dstMp3).size;
    }
  }
}

fs.writeFileSync(path.join(GD, 'units.ini.arcpatch'), patchLines.join('\r\n'), 'latin1');

// 3. Copy custom menu corner faces (pig_face_01..12.png, rabbit_face_01..14.png, raven_face_01..15.png)
let faceFiles = 0;
for (const srcFaces of [path.join(SRC, 'menu/faces'), path.join(RAVEN_SRC, 'menu/faces')]) {
  if (fs.existsSync(srcFaces)) {
    const dstFaces = path.join(GD, 'menu/faces');
    fs.mkdirSync(dstFaces, { recursive: true });
    for (const f of fs.readdirSync(srcFaces).filter(x => x.endsWith('.png')).sort()) {
      fs.copyFileSync(path.join(srcFaces, f), path.join(dstFaces, f));
      faceFiles++;
    }
  }
}

// 4. Build Stahlstadt Pig City menu_background.scene + ver=0 DXT1 display tanks + cameras.ini.arcpatch
const { execFileSync } = require('child_process');
execFileSync(process.execPath, [path.join(__dirname, 'build-menu-scene.js'), GD], { stdio: 'inherit' });
// Replace full cameras.ini with a clean cameras.ini.arcpatch so modpack stays non-destructive
const camIniPath = path.join(GD, 'cameras.ini');
if (fs.existsSync(camIniPath)) {
  const m = fs.readFileSync(camIniPath, 'latin1').match(/\[missions\/menu_background\.scene\][\s\S]*?(?=\r?\n\[|\s*$)/i);
  fs.rmSync(camIniPath, { force: true });
  if (m) {
    fs.writeFileSync(
      path.join(GD, 'cameras.ini.arcpatch'),
      '; Arcanum menu background camera (Stahlstadt pig city plaza)\r\n' + m[0].trim() + '\r\n',
      'latin1'
    );
  }
}

fs.writeFileSync(path.join(DST, 'README.md'), `# Arcanum Voices & Screens

Анимированные экранчики (портреты HUD), русская озвучка для всех 10 новых танков из **Arcanum Units**, свинский город Штадт с нашей техникой на фоне главного меню и портреты новых персонажей в правом нижнем углу меню.
Собирается скриптом \`node tools/build-voices-mod.js\` из исходников в \`modpack/voices/\`, руками \`gamedata/\` не править.

- \`gamedata/base/units.ini.arcpatch\` — назначает уникальные \`Character\` и \`Voice\` всем 10 новым юнитам поверх \`arcanum-units\`.
- \`gamedata/base/cameras.ini.arcpatch\` + \`missions/menu_background.scene\` + \`objects/arcanum_menu/*\` — фон главного меню в свинском городе Штадт с пред-окрашенными (DXT1, ver=0) моделями всех 10 новых танков.
- \`gamedata/base/menu/faces/*.png\` — ${faceFiles} прозрачных портретов новых свинов (\`pig_face_01..12.png\`) и кроликов (\`rabbit_face_01..14.png\`) для правого нижнего угла меню.
- \`gamedata/base/reportanim/<CharId>/*.anif\` — ${anifFiles} экранчиков (${(anifBytes / 1048576).toFixed(1)} МБ, 120×90 @ 25 FPS, полный набор из 7 эмоций: \`3mp\`, \`5mp\`, \`success\`, \`laugh\`, \`spec\`, \`death\`, \`death2\`, с ТВ-шумом при гибели).
- \`gamedata/base/sounds/speech/<CharId>/*.mp3\` — 300 уникальных реплик (Qwen3-TTS, 22050 Hz mono 48 kbps), разложенных по всем ${speechFiles} игровым ID событий (${(speechBytes / 1048576).toFixed(1)} МБ), включая раненые варианты \`*w.mp3\`.

Префиксы \`Character\` (\`P04\`–\`P08\` у свиней, \`R02\`/\`R03\`/\`R05\`/\`R06\`/\`R12\` у кроликов) подобраны по разбору \`SGameWorld::ShowEventMsg\`, чтобы движок проигрывал все 7 анимаций без патча exe.
`);

console.log(`arcanum-voices: ${anifFiles} ANIF (${(anifBytes / 1048576).toFixed(1)} MB) + ${speechFiles} speech MP3 (${(speechBytes / 1048576).toFixed(1)} MB) + ${faceFiles} menu faces + Stahlstadt menu scene → ${DST}`);
